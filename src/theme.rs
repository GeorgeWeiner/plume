#[cfg(test)]
mod tests {
    use super::*;

    fn rgb(c: Color) -> (f64, f64, f64) {
        match c {
            Color::Rgb(r, g, b) => (r as f64 / 255.0, g as f64 / 255.0, b as f64 / 255.0),
            _ => panic!("theme colors must be Rgb"),
        }
    }

    // WCAG relative luminance.
    fn lum(c: Color) -> f64 {
        let (r, g, b) = rgb(c);
        let f = |x: f64| if x <= 0.03928 { x / 12.92 } else { ((x + 0.055) / 1.055).powf(2.4) };
        0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
    }

    fn contrast(a: Color, b: Color) -> f64 {
        let (l1, l2) = (lum(a), lum(b));
        let (hi, lo) = if l1 > l2 { (l1, l2) } else { (l2, l1) };
        (hi + 0.05) / (lo + 0.05)
    }

    #[test]
    fn all_themes_are_legible_and_unique() {
        let themes = Theme::all();
        assert_eq!(themes.len(), 57, "expected 57 themes");

        let mut names = std::collections::HashSet::new();
        let mut bad: Vec<String> = Vec::new();
        for t in &themes {
            assert!(names.insert(t.name), "duplicate theme name: {}", t.name);

            let mut check = |ok: bool, what: &str, v: f64| {
                if !ok {
                    bad.push(format!("{}: {what} ({v:.2})", t.name));
                }
            };
            check(contrast(t.bg, t.fg) >= 4.0, "bg/fg too low", contrast(t.bg, t.fg));
            check(
                contrast(t.accent, t.accent_fg) >= 2.5,
                "accent/accent_fg too low",
                contrast(t.accent, t.accent_fg),
            );
            check(contrast(t.bg, t.line_nr) >= 1.25, "line_nr invisible", contrast(t.bg, t.line_nr));
            check(contrast(t.bg, t.dim) >= 1.5, "dim invisible", contrast(t.bg, t.dim));
            check(
                contrast(t.bg, t.selection) >= 1.08,
                "selection invisible",
                contrast(t.bg, t.selection),
            );
            check(
                contrast(t.bg, t.match_bg) >= 1.1,
                "match_bg invisible",
                contrast(t.bg, t.match_bg),
            );
        }
        assert!(bad.is_empty(), "theme legibility issues:\n  {}", bad.join("\n  "));
    }
}
